import {mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
await mkdir(new URL('../dist/demo/',import.meta.url),{recursive:true});
for(const file of ['app.js','style.css','forms.css'])await copyFile(`${root}web/${file}`,`${root}dist/${file}`);
const html=await readFile(`${root}web/index.html`,'utf8');
await writeFile(`${root}dist/demo/index.html`,html.replace('<body data-stage="read">','<body data-stage="read" data-hosted-demo="true">').replace('href="#start" aria-label="Navegante Web, início"','href="/" aria-label="Navegante Web, início"'));
await copyFile(`${root}web/landing.html`,`${root}dist/index.html`);
await copyFile(`${root}web/landing.css`,`${root}dist/landing.css`);
console.log('Desktop-download homepage built in dist/. Isolated demo available at /demo/.');
